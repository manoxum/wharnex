import { expect, test } from '@playwright/test'

test('pending changes offer accessible collective controls at narrow widths', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 850 })
  await page.goto('/e2e/git/changes/fixture.html')
  const input = page.getByRole('textbox', { name: 'Mensagem do commit' })
  await input.fill('fix: atualizar projeto')
  await expect(page.getByRole('button', { name: 'Commitar tudo' })).toBeEnabled()
  const combined = page.getByRole('button', { name: 'Commit e push' })
  await expect(combined).toBeEnabled()
  await input.focus()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Commitar tudo' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(combined).toBeFocused()
  const bounds = await combined.boundingBox()
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: /Executar operações em/ }).click()
  await expect(page.getByText('docs-clean', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /Executar operações em/ }).click()
  await page.screenshot({ path: '/tmp/wharnex-git-changes-narrow.png', fullPage: true })
})

test('commit and push reviews each phase and executes every affected repository children first', async ({ page }) => {
  await page.goto('/e2e/git/changes/fixture.html')
  await page.getByRole('textbox', { name: 'Mensagem do commit' }).fill('fix: atualizar projeto')
  await page.getByRole('button', { name: 'Commit e push' }).click()
  const confirm = page.getByRole('button', { name: 'Confirmar e continuar' })
  await expect(confirm).toBeVisible()
  await expect(page.getByLabel('Operações verificadas')).toHaveText('')
  await confirm.click()
  await expect(page.getByRole('dialog', { name: 'A enviar commits de todos os repositórios' })).toBeVisible()
  await expect(page.getByLabel('Operações verificadas')).toHaveText('commit:backend, commit:frontend, commit:root')
  await confirm.click()
  await expect(page.getByLabel('Operações verificadas')).toHaveText('commit:backend, commit:frontend, commit:root, push:backend, push:frontend, push:root')
  await expect(page.getByRole('button', { name: 'Enviar commits', exact: true })).toBeDisabled()
})

test('complete push reviews every repository once and remains usable at narrow widths', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 850 })
  await page.goto('/e2e/git/changes/fixture.html')
  const button = page.getByRole('button', { name: 'Publicar projeto', exact: true })
  await expect(button).toBeEnabled()
  await button.focus()
  await expect(button).toBeFocused()
  const bounds = await button.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: '/tmp/wharnex-complete-push-narrow.png', fullPage: true })
  await page.keyboard.press('Enter')
  const review = page.getByRole('dialog', { name: 'Push completo do projeto' })
  await expect(review).toBeVisible()
  await expect(review.getByRole('navigation', { name: 'Repositórios revistos' })).toContainText('docs-clean')
  await expect(page.getByLabel('Operações verificadas')).toHaveText('')
  await review.getByRole('button', { name: 'Confirmar e continuar' }).click()
  await expect(page.getByLabel('Operações verificadas')).toHaveText('push:backend, push:docs-clean, push:frontend, push:root')
  await expect(page.getByText(/Envio concluído em 4 repositório/, { exact: false }).first()).toBeVisible()
})
