import { expect, test } from '@playwright/test'

for (const theme of ['light', 'dark']) {
  test(`tabs adapt to their container with blue selection in ${theme}`, async ({ page }) => {
    await page.route('**/ui-testing*', async (route) => {
      if (!route.request().url().includes('tabs-fixture')) return route.continue()
      await route.fulfill({ json: { tests: [], guides: [], environments: [], runs: [], design_tasks: [], config: {}, manuals: [] } })
    })
    await page.route('**/automation-holds*', (route) => route.fulfill({ json: { holds: [] } }))
    await page.goto('/e2e/tabs/fixture.html')
    await page.evaluate((theme) => { document.documentElement.dataset.theme = theme; document.documentElement.dataset.uiAccent = 'orange' }, theme)
    const strip = page.getByRole('tablist', { name: 'Referência Git' })
    await expect(strip).toHaveAttribute('data-density', 'full')
    const selected = strip.getByRole('tab', { name: 'Alterações' })
    const underline = await selected.evaluate((tab) => ({ color: getComputedStyle(tab, '::after').backgroundColor, height: getComputedStyle(tab, '::after').height, font: getComputedStyle(tab).fontSize, borderRadius: getComputedStyle(tab).borderRadius }))
    expect(underline.color).toBe(theme === 'light' ? 'rgb(53, 116, 240)' : 'rgb(94, 156, 255)')
    expect(underline.height).toBe('2px')
    expect(underline.borderRadius).toBe('0px')
    expect(parseFloat(underline.font)).toBeLessThan(16)
    await page.locator('#strip-owner').evaluate((owner) => { owner.style.width = '400px' })
    await expect(strip).toHaveAttribute('data-density', 'compact')
    await expect(selected.locator('[data-tab-label]')).toBeHidden()
    await expect(selected.locator('[data-tab-badge]')).toBeVisible()
    await page.locator('#strip-owner').evaluate((owner) => { owner.style.width = '220px' })
    await expect(strip).toHaveAttribute('data-density', 'icons')
    await expect(selected.locator('[data-tab-icon]')).toBeVisible()
    await expect(selected.locator('[data-tab-badge]')).toBeHidden()
    await selected.focus(); await page.keyboard.press('ArrowRight')
    await expect(strip.getByRole('tab', { name: 'Histórico' })).toBeFocused()
    await expect(strip.getByRole('tab', { name: 'Histórico' })).toHaveAttribute('aria-selected', 'true')
    await page.locator('#strip-owner').evaluate((owner) => { owner.style.width = '800px' })
    await expect(strip).toHaveAttribute('data-density', 'full')
    await expect(selected.locator('[data-tab-label]')).toBeVisible()
    await page.evaluate(() => document.documentElement.style.setProperty('--ui-font-scale', '2'))
    await page.locator('#strip-owner').evaluate((owner) => { owner.style.width = '500px' })
    await expect(strip).toHaveAttribute('data-density', 'compact')
    const surfaces = page.getByRole('tablist', { name: 'Áreas do Agent' })
    await expect(surfaces).toHaveAttribute('data-density', 'icons')
    await expect(surfaces.locator('[data-tab-label]').first()).toBeHidden()
    await expect(surfaces.getByRole('tab', { selected: true })).toHaveCount(1)
    await expect(surfaces.getByRole('tab', { name: 'Chat' })).toHaveAttribute('aria-selected', 'true')
    await surfaces.getByRole('tab', { name: 'Engine' }).click()
    await expect(surfaces.getByRole('tab', { selected: true })).toHaveCount(1)
    await surfaces.getByRole('tab', { name: 'Chat' }).click()
    await expect(surfaces.getByRole('tab', { selected: true })).toHaveCount(1)
    await expect(surfaces.getByRole('tab', { name: 'Engine' })).toHaveAttribute('aria-selected', 'false')
    for (const name of ['Ficheiros abertos', 'Instâncias do terminal']) {
      const resources = page.getByRole('tablist', { name })
      const bounds = await resources.boundingBox()
      if (name === 'Instâncias do terminal') expect(bounds?.height).toBe(34)
      else expect(bounds?.height).toBe(35)
      await expect(resources.getByRole('tab', { selected: true })).toHaveCount(1)
      const closeActions = resources.getByRole('button', { name: /Fechar/ })
      await expect(closeActions).toHaveCount(name === 'Ficheiros abertos' ? 2 : 1)
      for (const action of await closeActions.all()) await expect(action).toBeVisible()
    }
    const browser = page.getByRole('tablist', { name: 'Visões dos navegadores' })
    await expect(browser.getByRole('tab', { name: 'Instâncias' }).locator('[data-tab-icon] svg')).toBeVisible()
    const lab = page.getByRole('tablist', { name: 'Áreas do UI Lab' })
    await expect(lab.getByRole('tab', { name: 'Testes UI' })).toHaveAttribute('aria-selected', 'true')
    await lab.getByRole('tab', { name: 'Documentação' }).click()
    await expect(page.getByRole('tablist', { name: 'Vista da documentação' })).toBeVisible()
    await page.locator('#lab-owner').evaluate((owner) => { owner.style.width = '130px' })
    await expect(lab).toHaveAttribute('data-density', 'icons')
    await page.locator('#lab-owner').evaluate((owner) => { owner.style.width = '560px' })
    await expect(lab).toHaveAttribute('data-density', 'full')
  })
}
