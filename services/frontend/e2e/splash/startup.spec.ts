import { expect, test } from '@playwright/test'
import { splashPage } from '../../../desktop/splash/view/index.mjs'

type SplashEntry = { stream: string; source: string; text: string; at: string }
declare global {
  interface Window { setSplashState: (state: { status: string; entries: SplashEntry[]; latest?: SplashEntry; append?: boolean; from?: number; failed: boolean }) => { collapsed: boolean; copy: boolean }; setCopyResult: (success: boolean) => void }
}

const rows = Array.from({ length: 120 }, (_, i) => ({ stream: i === 3 ? 'stderr' : 'stdout', source: 'make', text: `Passo ${i} · A preparar o espaço de trabalho`, at: '2026-10-06T12:05:30Z' }))

test('splash shows safe live stdout/stderr, preserves scrollback and exposes failure', async ({ page }) => {
  await page.setViewportSize({ width: 700, height: 375 })
  await page.setContent(splashPage('v1.2.64.1'))
  for (const region of ['header', '.content']) {
    expect(await page.locator(region).evaluate((element) => getComputedStyle(element).getPropertyValue('app-region'))).toBe('drag')
  }
  expect(await page.locator('#close').evaluate((element) => getComputedStyle(element).getPropertyValue('app-region'))).toBe('no-drag')
  expect(await page.locator('.output').evaluate((element) => getComputedStyle(element).getPropertyValue('app-region'))).toBe('no-drag')
  await expect(page.getByRole('button', { name: 'Copiar saída do arranque' })).toBeDisabled()
  await expect(page.locator('#logs')).toBeHidden()
  await expect(page.getByRole('button', { name: 'Expandir registos de arranque' })).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: 'Expandir registos de arranque' }).click()
  await page.setViewportSize({ width: 700, height: 570 })
  await page.evaluate((entries) => window.setSplashState({ status: 'A compilar a nova versão…', entries, failed: false }), rows)
  await expect(page.locator('.line[data-stream="stdout"]')).toHaveCount(119)
  await expect(page.locator('.line[data-stream="stderr"]')).toHaveCount(1)
  await expect(page.locator('.line').last()).toBeInViewport()
  await page.getByRole('button', { name: 'Copiar saída do arranque' }).click()
  const requested = await page.evaluate((entries) => window.setSplashState({ status: 'A compilar…', entries, failed: false }), rows)
  expect(requested.copy).toBe(true)
  await expect(page.locator('#copy-output svg')).toBeVisible()
  await expect(page.locator('#copy-output')).toHaveText('')
  const positions = await page.locator('.output-heading').evaluate((heading) => [...heading.querySelectorAll('button')].map((button) => button.id))
  expect(positions).toEqual(['copy-output', 'toggle-output'])
  const copyBounds = await page.locator('#copy-output').boundingBox()
  const toggleBounds = await page.locator('#toggle-output').boundingBox()
  expect(copyBounds!.x + copyBounds!.width).toBeLessThan(toggleBounds!.x)
  const consumed = await page.evaluate((entries) => window.setSplashState({ status: 'A compilar…', entries, failed: false }), rows)
  expect(consumed.copy).toBe(false)
  await page.evaluate(() => window.setCopyResult(true))
  await expect(page.getByRole('button', { name: 'Copiar saída do arranque' })).toHaveAttribute('title', 'Saída copiada')
  await expect(page.locator('#copy-output svg')).toBeVisible()
  await page.evaluate(() => window.setCopyResult(false))
  await expect(page.locator('#copy-output')).toHaveAttribute('title', 'Não foi possível copiar · tentar de novo')
  await expect(page.locator('#copy-output svg')).toBeVisible()
  await expect(page.locator('#copy-output')).toHaveText('')
  await expect(page.getByText('stdout', { exact: true })).toHaveCount(0)
  await expect(page.getByText('stderr', { exact: true })).toHaveCount(0)
  const errorBackground = await page.locator('.line[data-stream="stderr"]').evaluate((line) => getComputedStyle(line).backgroundColor)
  expect(errorBackground).toBe('rgba(184, 68, 68, 0.19)')
  await page.getByRole('button', { name: 'Recolher registos de arranque' }).click()
  await expect(page.locator('#logs')).toBeHidden()
  await expect(page.getByRole('button', { name: 'Expandir registos de arranque' })).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('#latest-output')).toBeVisible()
  await expect(page.locator('#latest-output .text')).toHaveText(rows.at(-1).text)
  await page.evaluate((entries) => window.setSplashState({ status: 'A iniciar…', entries, failed: false }), [...rows, { ...rows[0], stream: 'stderr', text: 'Última linha capturada' }])
  await expect(page.locator('#latest-output .text')).toHaveText('Última linha capturada')
  expect(await page.locator('#latest-output').evaluate((element) => getComputedStyle(element).backgroundColor)).toBe('rgba(184, 68, 68, 0.19)')
  await page.getByRole('button', { name: 'Expandir registos de arranque' }).click()
  await expect(page.locator('#logs')).toBeVisible()
  const logs = page.locator('#logs')
  await logs.evaluate((element) => { element.scrollTop = 0; element.dispatchEvent(new Event('scroll')) })
  await page.evaluate((entries) => window.setSplashState({ status: 'A iniciar o Desktop…', entries, failed: false }), [...rows, { ...rows[0], text: '<img src=x onerror="window.unsafe=true">' }])
  await expect(page.getByText('Desloca para o fim para acompanhar a saída')).toBeVisible()
  expect(await logs.evaluate((element) => element.scrollTop)).toBe(0)
  await expect(logs.locator('img')).toHaveCount(0)
  await logs.evaluate((element) => { element.scrollTop = element.scrollHeight; element.dispatchEvent(new Event('scroll')) })
  await page.evaluate(() => window.setSplashState({ status: 'O Wharnex não iniciou. Consulta a saída abaixo.', entries: [{ stream: 'stderr', source: 'make', text: 'Falha ao compilar o frontend · código de saída 2', at: '2026-10-06T12:06:01Z' }], failed: true }))
  await expect(page.getByText('Falha no arranque · consulta os registos')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Fechar' })).toBeVisible()
  await expect(page.locator('#logs').getByText('Falha ao compilar o frontend · código de saída 2')).toBeVisible()
  await page.getByRole('button', { name: 'Recolher registos de arranque' }).click()
  await page.setViewportSize({ width: 700, height: 375 })
  await expect(page.locator('#latest-output .text')).toHaveText('Falha ao compilar o frontend · código de saída 2')
  await expect(page.locator('#logs')).toBeHidden()
  const contentFits = await page.evaluate(() => document.querySelector('main').scrollHeight <= window.innerHeight)
  expect(contentFits).toBe(true)
  await page.screenshot({ path: '/tmp/wharnex-splash-preview.png' })
})
