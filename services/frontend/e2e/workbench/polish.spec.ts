test('supporting tools protect the primary workspace and restore preferred sizes after a compact window', async ({ page }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.addInitScript(() => localStorage.setItem('whx.workbench.layout.v1:/workspace/atlas', JSON.stringify({ version: 1, left: { open: true, size: 480, tool: 'docker' }, right: { open: true, size: 600, tool: 'database' }, bottom: { open: false, size: 300 } })))
  await page.goto('/e2e/workbench/fixture.html')
  const primary = page.locator('.workspace-center-column')
  expect((await primary.boundingBox())!.width).toBeGreaterThanOrEqual(560)
  const left = page.locator('.workspace-side-drawer-left:not([hidden])')
  const initialWidth = (await left.boundingBox())!.width
  await page.getByRole('separator', { name: 'Redimensionar painel lateral esquerdo', exact: true }).press('ArrowRight')
  await expect.poll(async () => (await left.boundingBox())!.width).toBe(initialWidth + 16)
  expect(await page.evaluate(() => localStorage.getItem('wharnex.workbench.panel-priority.v1:/workspace/atlas'))).toBe('left')
  const divider = await page.getByRole('separator', { name: 'Redimensionar painel lateral esquerdo', exact: true }).boundingBox()
  await page.mouse.move(divider!.x + 3, divider!.y + 40)
  await page.mouse.down()
  await page.mouse.move(divider!.x + 27, divider!.y + 40)
  await page.mouse.up()
  await expect.poll(async () => (await left.boundingBox())!.width).toBe(initialWidth + 40)
  expect(await page.evaluate(() => ({ cursor: document.body.style.cursor, selection: document.body.style.userSelect }))).toEqual({ cursor: '', selection: '' })
  await page.setViewportSize({ width: 1100, height: 800 })
  const right = page.locator('.workspace-side-drawer-right:not([hidden])')
  await expect(right).toHaveAttribute('data-panel-overlay', 'true')
  expect((await primary.boundingBox())!.width).toBeGreaterThanOrEqual(460)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('whx.workbench.layout.v1:/workspace/atlas')!).right.size)).toBe(600)
  await page.screenshot({ path: 'test-results/polish-supporting-overlay.png' })
  for (const width of [1280, 1281, 1282, 1290, 1280, 900, 800, 700]) {
    await page.setViewportSize({ width, height: 800 })
    await expect.poll(async () => (await primary.boundingBox())!.width).toBeGreaterThanOrEqual(Math.min(560, Math.max(360, Math.round(width * 0.42))))
  }
  await page.setViewportSize({ width: 1920, height: 1080 })
  await expect(right).toHaveAttribute('data-panel-overlay', 'false')
  expect((await right.boundingBox())!.width).toBe(600)
})

test('visual matrix keeps one workbench at compact, normal and maximized desktop dimensions', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/e2e/workbench/fixture.html?changes=1')
  await expect(page.getByRole('tab', { name: 'app.ts' })).toBeVisible()
  await page.screenshot({ path: 'test-results/polish-explorer-editor.png' })
  await page.getByRole('button', { name: 'Alternar painel esquerdo', exact: true }).click()
  await page.screenshot({ path: 'test-results/polish-editor-alone.png' })
  await page.getByRole('button', { name: 'Git do projeto', exact: true }).click()
  await expect(page.getByRole('textbox', { name: /Mensagem.*commit/i })).toBeVisible()
  expect((await page.getByRole('textbox', { name: /Mensagem.*commit/i }).boundingBox())!.height).toBeLessThanOrEqual(36)
  await page.screenshot({ path: 'test-results/polish-git-editor.png' })
  await page.getByRole('button', { name: 'Docker', exact: true }).click()
  await page.getByRole('button', { name: /Compose/ }).first().click()
  await page.getByRole('button', { name: 'Expandir Compose atlas' }).click()
  await expect(page.getByRole('button', { name: 'Ver detalhes do container atlas-api' })).toBeVisible()
  await page.screenshot({ path: 'test-results/polish-docker-editor.png' })
  await page.getByRole('button', { name: 'Agent', exact: true }).click()
  await page.locator('.ql-editor[contenteditable=true]').fill('Rever a implementação e preservar o contexto atual.')
  await page.screenshot({ path: 'test-results/polish-agent.png' })
  await page.getByRole('button', { name: 'Orchestrator', exact: true }).click()
  await expect(page.locator('.orchestrator-workspace')).toBeVisible()
  await page.screenshot({ path: 'test-results/polish-orchestrator.png' })
  await page.getByRole('button', { name: 'Editor', exact: true }).click()
  await page.getByRole('tab', { name: 'Terminal', exact: true }).click()
  await expect(page.getByTestId('fixture-terminal')).toBeVisible()
  await page.screenshot({ path: 'test-results/polish-terminal.png' })
  await page.getByRole('button', { name: 'Configuração do projeto', exact: true }).click()
  await page.screenshot({ path: 'test-results/polish-settings.png' })
  await page.getByRole('button', { name: 'Fechar configurações', exact: true }).click()
  for (const [name, width, height] of [['compact', 900, 700], ['maximized', 1920, 1080]] as const) {
    await page.setViewportSize({ width, height })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    const header = page.locator('.workspace-topbar')
    const bounds = (await header.boundingBox())!
    for (const child of await header.locator(':scope > div').all()) {
      const box = (await child.boundingBox())!
      expect(box.y).toBeGreaterThanOrEqual(bounds.y)
      expect(box.y + box.height).toBeLessThanOrEqual(bounds.y + bounds.height)
    }
    expect((await page.locator('.workspace-main-row').boundingBox())!.y).toBeGreaterThanOrEqual(bounds.y + bounds.height)
    await page.screenshot({ path: `test-results/polish-${name}.png` })
  }
})
