import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('**/api/**', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: '{}' }))
  await page.setViewportSize({ width: 1440, height: 900 })
})
test('Search Everywhere opens actual files from combined results and preserves keyboard focus', async ({ page }) => {
  await page.goto('/e2e/workbench/fixture.html')
  await page.getByRole('button', { name: 'Pesquisar e executar comandos' }).click()
  const query = page.getByRole('combobox', { name: 'Pesquisar comandos' })
  await query.fill('readme')
  await expect(page.getByRole('option', { name: /README.md/ })).toBeVisible()
  await page.screenshot({ path: 'test-results/professional-search.png' })
  await query.press('Enter')
  await expect(page.getByRole('tab', { name: 'README.md' })).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Pesquisar e executar comandos' })).toBeHidden()
})
test('tool maximize restores its exact width and mounted editor after Escape', async ({ page }) => {
  await page.goto('/e2e/workbench/fixture.html')
  const drawer = page.locator('.workspace-side-drawer-left:not([hidden])')
  const width = (await drawer.boundingBox())!.width
  await page.getByRole('button', { name: 'Opções do painel Explorador do projeto' }).click()
  await page.getByRole('button', { name: 'Maximizar painel', exact: true }).click()
  await expect(drawer).toHaveAttribute('data-panel-maximized', 'true')
  expect((await drawer.boundingBox())!.width).toBe(1440)
  await page.screenshot({ path: 'test-results/professional-tool-maximized.png' })
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveAttribute('data-panel-maximized', 'false')
  expect((await drawer.boundingBox())!.width).toBe(width)
  await expect(page.getByRole('tab', { name: 'app.ts' })).toBeVisible()
})
test('Zen hides chrome, keeps document state and restores the chosen layout', async ({ page }) => {
  await page.goto('/e2e/workbench/fixture.html')
  const drawer = page.locator('.workspace-side-drawer-left:not([hidden])')
  const width = (await drawer.boundingBox())!.width
  await page.keyboard.press('Control+Shift+P')
  await page.getByRole('combobox', { name: 'Pesquisar comandos' }).fill('sem distracoes')
  await page.getByRole('combobox', { name: 'Pesquisar comandos' }).press('Enter')
  await expect(page.locator('.workspace-topbar')).toBeHidden()
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('tab', { name: 'app.ts' })).toBeVisible()
  const save = (await page.getByRole('button', { name: 'Guardar agora', exact: true }).boundingBox())!
  const exit = (await page.getByRole('button', { name: 'Sair do modo sem distrações · Esc', exact: true }).boundingBox())!
  expect(save.x + save.width).toBeLessThanOrEqual(exit.x)
  await page.screenshot({ path: 'test-results/professional-zen.png' })
  await page.getByRole('button', { name: 'Sair do modo sem distrações · Esc', exact: true }).click()
  await expect(page.locator('.workspace-topbar')).toBeVisible()
  expect((await drawer.boundingBox())!.width).toBe(width)
})
