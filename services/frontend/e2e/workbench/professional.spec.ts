test('evolution timeline preserves filters, event selection and lazy technical payload', async ({ page }) => {
  await page.goto('/e2e/workbench/fixture.html?professional=1')
  await page.getByRole('button', { name: 'Logs de auto-evolução', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dossiê de evolução', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Opções do painel Logs de auto-evolução' }).click()
  await page.getByRole('button', { name: 'Maximizar painel', exact: true }).click()
  await page.getByLabel('Selecionar evento execution.failed', { exact: true }).check()
  await page.getByText('Dados', { exact: true }).first().click()
  await expect(page.locator('pre').filter({ hasText: 'A verificação detetou' })).toBeVisible()
  await page.screenshot({ path: 'test-results/professional-dossier.png' })
  await page.getByRole('combobox', { name: 'Filtrar categoria' }).selectOption('verification')
  await expect(page.getByLabel('Selecionar evento verification.started', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Selecionar evento execution.failed', { exact: true })).toBeHidden()
})

test('compact density keeps test typography readable while reducing row height', async ({ page }) => {
  await page.goto('/e2e/workbench/fixture.html?professional=1&density=compact&theme=light')
  await page.getByRole('button', { name: 'UI Lab', exact: true }).click()
  await page.getByRole('button', { name: 'Opções do painel UI Lab' }).click()
  await page.getByRole('button', { name: 'Maximizar painel', exact: true }).click()
  const scenario = page.getByRole('article', { name: 'Abrir um documento no editor', exact: true })
  expect((await scenario.boundingBox())!.height).toBeLessThanOrEqual(32)
  expect(await scenario.locator('strong').evaluate((element) => parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(12)
  await page.getByRole('checkbox', { name: 'Selecionar Abrir um documento no editor' }).check()
  await page.getByText('Abrir um documento no editor', { exact: true }).click()
  await expect(page.getByText('Código visível', { exact: false })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Selecionar Abrir um documento no editor' })).toBeChecked()
  await page.screenshot({ path: 'test-results/professional-tests-density-compact-light.png' })
})
