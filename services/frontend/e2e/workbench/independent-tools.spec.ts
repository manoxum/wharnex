import { expect, test } from '@playwright/test'
for (const theme of ['light', 'dark']) for (const density of ['default', 'compact']) {
  test(`independent tools preserve the terminal and release editor space in ${theme}/${density}`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.route('**/api/**', (route) => route.fulfill({ json: {} }))
    await page.goto(`/e2e/workbench/fixture.html?theme=${theme}&density=${density}`)
    const panel = page.locator('.workbench-operational-panel')
    await expect(page.getByRole('tab', { name: 'app.ts', exact: true })).toBeVisible()
    expect((await panel.boundingBox())!.height).toBe(0)
    const terminal = page.getByTestId('fixture-terminal')
    await terminal.evaluate((node) => node.setAttribute('data-lifecycle-check', 'preserved'))
    await page.getByRole('button', { name: 'Abrir terminal', exact: true }).click()
    await expect(terminal).toBeVisible()
    await page.getByRole('button', { name: 'Problemas', exact: true }).click()
    await expect(page.getByText('Sem diagnósticos de código', { exact: true })).toBeVisible()
    await expect(terminal).toBeHidden()
    await page.getByRole('button', { name: 'Saída de execução', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Saída de execução', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Acoplar à direita' }).click()
    await expect(page.getByRole('button', { name: 'Acoplar em baixo' })).toBeVisible()
    expect(await panel.evaluate((node) => getComputedStyle(node.parentElement!).display)).toBe('grid')
    await page.getByRole('button', { name: 'Recolher ferramentas operacionais' }).click()
    await expect(panel).toHaveAttribute('data-expanded', 'false')
    expect((await panel.boundingBox())!.height).toBe(0)
    await page.getByRole('button', { name: /terminal$/i }).first().click()
    await expect(terminal).toBeVisible()
    await expect(terminal).toHaveAttribute('data-lifecycle-check', 'preserved')
    await page.screenshot({ path: `test-results/independent-${theme}-${density}.png` })
  })
}
test('document context actions stay within the viewport and preserve pinned files during batch close', async ({ page }) => {
  await page.setViewportSize({ width: 1000, height: 700 })
  await page.route('**/api/**', (route) => route.fulfill({ json: {} }))
  await page.goto('/e2e/workbench/fixture.html')
  const tab = page.getByRole('tab', { name: 'app.ts', exact: true })
  await tab.click({ button: 'right' })
  const menu = page.getByRole('menu', { name: 'Ações de src/app.ts' })
  await expect(menu).toBeVisible()
  const box = (await menu.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0); expect(box.y + box.height).toBeLessThanOrEqual(700)
  await page.getByRole('menuitem', { name: 'Fixar separador', exact: true }).click()
  await tab.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Fechar todos', exact: true }).click()
  await expect(tab).toBeVisible()
  await tab.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Fechar atual', exact: true }).click()
  await expect(tab).toHaveCount(0)
})
test('code problems are actual Monaco diagnostics and stay distinct from runtime incidents', async ({ page }) => {
  await page.route('**/api/**', (route) => route.fulfill({ json: {} }))
  await page.goto('/e2e/workbench/fixture.html')
  await expect(page.getByRole('tab', { name: 'app.ts', exact: true })).toBeVisible()
  await page.waitForFunction(() => Boolean((window as unknown as { monaco?: { editor?: unknown } }).monaco?.editor))
  await page.evaluate(() => {
    const runtime = (window as unknown as { monaco: typeof import('monaco-editor') }).monaco
    const model = runtime.editor.getModels().find((item) => item.uri.path === '/src/app.ts')!
    runtime.editor.setModelMarkers(model, 'ux-test', [{ severity: runtime.MarkerSeverity.Error, message: 'Diagnóstico de integração', source: 'TypeScript', startLineNumber: 1, startColumn: 1, endLineNumber: 1, endColumn: 6 }])
  })
  const trigger = page.getByRole('button', { name: 'Problemas', exact: true })
  await expect(trigger).toContainText('1')
  await trigger.click()
  await expect(page.getByText('Diagnóstico de integração', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Filtrar problemas' }).fill('sem correspondência')
  await expect(page.getByText('Sem correspondências', { exact: true })).toBeVisible()
})
test('quick appearance applies themes, accents and density immediately in a bounded popup', async ({ page }) => {
  await page.setViewportSize({ width: 1000, height: 700 })
  await page.route('**/api/**', (route) => route.fulfill({ json: {} }))
  await page.goto('/e2e/workbench/fixture.html')
  const trigger = page.getByRole('button', { name: 'Aparência rápida', exact: true })
  await trigger.click()
  const popup = page.getByRole('dialog', { name: 'Aparência rápida', exact: true })
  const bounds = (await popup.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(1000)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(700)
  await page.getByRole('combobox', { name: 'Tema da interface' }).selectOption('vscode-light')
  await expect(page.locator('html')).toHaveAttribute('data-ui-theme', 'vscode-light')
  await page.getByRole('button', { name: 'Destaque: Laranja', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-ui-accent', 'orange')
  await page.getByRole('button', { name: 'Densidade: Compacta', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-density', 'compact')
  await expect(page.getByRole('button', { name: 'Densidade: Compacta', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: 'test-results/independent-appearance.png' })
  await page.keyboard.press('Escape')
  await expect(popup).toHaveCount(0)
  await expect(trigger).toBeFocused()
})
test('dirty document confirmation cancels safely and discards only on explicit choice', async ({ page }) => {
  await page.setViewportSize({ width: 1200, height: 800 })
  await page.route('**/api/**', (route) => route.fulfill({ json: {} }))
  await page.route('**/api/sessions/workbench-fixture/file', (route) => route.fulfill({ status: 409, json: { error: 'Gravação indisponível nesta fixture' } }))
  await page.goto('/e2e/workbench/fixture.html')
  const tab = page.getByRole('tab', { name: 'app.ts', exact: true })
  await expect(tab).toBeVisible()
  await page.waitForFunction(() => Boolean((window as unknown as { monaco?: { editor?: unknown } }).monaco?.editor))
  await page.evaluate(() => {
    const runtime = (window as unknown as { monaco: typeof import('monaco-editor') }).monaco
    runtime.editor.getModels().find((item) => item.uri.path === '/src/app.ts')!.setValue('export const edited = true')
  })
  await expect(tab.locator('.dirty-dot')).toBeVisible()
  await tab.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Fechar atual', exact: true }).click()
  const dialog = page.getByRole('alertdialog', { name: 'Guardar alterações?', exact: true })
  await expect(dialog).toBeVisible()
  expect((await dialog.boundingBox())!.width).toBeLessThanOrEqual(440)
  await expect(dialog.getByRole('button', { name: 'Cancelar', exact: true })).toBeFocused()
  await page.screenshot({ path: 'test-results/independent-save-confirmation.png' })
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(tab).toBeVisible()
  await expect(tab.locator('.dirty-dot')).toBeVisible()
  await tab.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Fechar atual', exact: true }).click()
  await dialog.getByRole('button', { name: 'Não guardar', exact: true }).click()
  await expect(tab).toHaveCount(0)
})
