import { expect, test } from '@playwright/test'
for (const theme of ['dark', 'light']) for (const density of ['default', 'compact']) {
  test(`open files stay bounded and keyboard accessible in ${theme}/${density}`, async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 720 })
    await page.goto(`/e2e/workbench/fixture.html?surface=documents&lang=en&theme=${theme}&density=${density}`)
    const rail = page.locator('.workspace-side-rail-left')
    const content = page.getByTestId('content')
    const pane = page.getByTestId('tool-pane')
    const background = (locator: typeof rail) => locator.evaluate((element) => getComputedStyle(element).backgroundColor)
    expect(await background(rail)).not.toBe(await background(content))
    expect(await background(pane)).not.toBe(await background(content))
    expect(await background(rail)).not.toBe(await background(pane))
    const activeTool = rail.getByRole('button', { name: 'Project explorer', exact: true })
    expect(await background(activeTool)).not.toBe(await background(rail.getByRole('button', { name: 'Project Git', exact: true })))
    await expect(activeTool).toHaveAttribute('aria-pressed', 'true')
    const trigger = page.getByRole('button', { name: 'Select open file (70)' })
    await trigger.click()
    const popup = page.getByRole('dialog', { name: 'Open files' })
    const bounds = (await popup.boundingBox())!
    expect(bounds.width).toBe(420)
    expect(bounds.height).toBeLessThanOrEqual(504)
    expect(bounds.y + bounds.height).toBeLessThanOrEqual(720)
    await expect(popup.getByRole('option', { selected: true })).toBeVisible()
    const search = popup.getByRole('combobox', { name: 'Search open files' })
    await expect(search).toBeFocused()
    expect((await search.boundingBox())!.height).toBe(32)
    const initialY = (await search.boundingBox())!.y
    await popup.getByRole('listbox').evaluate((element) => { element.scrollTop = element.scrollHeight })
    expect((await search.boundingBox())!.y).toBe(initialY)
    await search.fill('feature-3/')
    await expect(popup.getByRole('option')).toHaveCount(1)
    await expect(popup.getByLabel('Unsaved changes')).toBeVisible()
    await search.press('Enter')
    await expect(page.getByTestId('selected-file')).toContainText('LongDocumentName3.tsx')
    await expect(popup).toHaveCount(0)
    await expect(trigger).toBeFocused()
    await trigger.click()
    await expect(search).toHaveValue('')
    await search.press('ArrowDown')
    await search.press('Enter')
    await expect(page.getByTestId('selected-file')).toContainText('LongDocumentName4.tsx')
    await trigger.click()
    await page.screenshot({ path: `test-results/open-files-${theme}-${density}.png` })
  })
}
test('switches and persists language without resetting the selected document', async ({ page }) => {
  await page.goto('/e2e/workbench/fixture.html?surface=documents&lang=en')
  await page.getByRole('button', { name: 'Select open file (70)' }).click()
  await page.getByRole('combobox', { name: 'Search open files' }).fill('Guardar')
  await page.getByRole('combobox', { name: 'Search open files' }).press('Enter')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  const selected = await page.getByTestId('selected-file').textContent()
  await page.getByRole('combobox', { name: 'Interface language' }).selectOption('pt')
  await page.getByRole('button', { name: 'Save languages', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Definições', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Idioma da interface' })).toHaveValue('pt')
  await expect(page.getByTestId('selected-file')).toHaveText(selected!)
  await page.goto('/e2e/workbench/fixture.html?surface=documents')
  await expect(page.getByRole('button', { name: 'Definições', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'pt-PT')
})

test('native Wharnex palette keeps the popup inside a resized small window', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.setViewportSize({ width: 800, height: 480 })
  await page.goto('/e2e/workbench/fixture.html?surface=documents&lang=en&palette=original')
  await page.getByRole('button', { name: 'Select open file (70)' }).click()
  const popup = page.getByRole('dialog', { name: 'Open files' })
  for (const viewport of [{ width: 800, height: 480 }, { width: 640, height: 400 }]) {
    await page.setViewportSize(viewport)
    await expect.poll(async () => {
      const bounds = (await popup.boundingBox())!
      return bounds.x >= 8 && bounds.y >= 8 && bounds.x + bounds.width <= viewport.width - 8 && bounds.y + bounds.height <= viewport.height - 8 && bounds.height <= viewport.height * 0.7
    }).toBe(true)
    await expect(popup.getByRole('combobox')).toBeVisible()
    await expect(popup.getByRole('option', { selected: true })).toBeVisible()
  }
  await page.screenshot({ path: 'test-results/open-files-original-small.png' })
  await page.keyboard.press('Escape')
  await expect(popup).toHaveCount(0)
})
