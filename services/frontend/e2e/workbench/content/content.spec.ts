import { expect, test } from '@playwright/test'
for (const theme of ['dark', 'light']) for (const density of ['default', 'compact']) {
  test(`content has a balanced hierarchy and English controls in ${theme}/${density}`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(`/e2e/workbench/fixture.html?surface=content&lang=en&theme=${theme}&density=${density}`)
    const knowledge = page.getByTestId('knowledge')
    await expect(knowledge.getByRole('heading', { name: 'Project knowledge' })).toBeVisible()
    await expect(knowledge.getByRole('button', { name: /Guardar/ })).toBeVisible()
    await expect(knowledge.getByRole('combobox', { name: 'Filter knowledge category' })).toBeVisible()
    await expect(knowledge.getByText('O conteúdo original fica em Português.')).toBeVisible()
    await expect(page.getByTestId('agent').getByText('Listening', { exact: true })).toBeVisible()
    const size = (locator: ReturnType<typeof page.locator>) => locator.evaluate((node) => parseFloat(getComputedStyle(node).fontSize))
    expect((await knowledge.locator('.whx-panel-heading').boundingBox())!.height).toBeLessThanOrEqual(density === 'compact' ? 38 : 42)
    const body = await size(knowledge.locator('.markdown-content p').first())
    const metadata = await size(knowledge.locator('time'))
    const title = await size(knowledge.getByRole('heading', { name: 'Project knowledge' }))
    const major = await size(page.getByTestId('major-title'))
    expect(body).toBeGreaterThanOrEqual(13); expect(body).toBeLessThanOrEqual(14.5)
    expect(metadata).toBeGreaterThanOrEqual(11.5); expect(metadata).toBeLessThanOrEqual(13.5)
    expect(title).toBeGreaterThan(body); expect(title).toBeLessThanOrEqual(16)
    expect(major).toBeGreaterThan(title); expect(major).toBeLessThanOrEqual(19)
    expect(await size(page.getByTestId('agent').locator('dd').first())).toBeCloseTo(body, 1)
    await expect(page.getByText('This introduction is available on hover.')).toHaveCount(0)
    await expect(page.getByRole('heading', { name: 'Editor settings' })).toHaveAttribute('title', 'This introduction is available on hover.')
    await page.getByRole('button', { name: 'Notifications', exact: true }).click()
    const alerts = page.getByRole('dialog', { name: 'Active notifications' })
    await expect(alerts.getByText('Attention', { exact: true })).toBeVisible()
    await expect(alerts.getByRole('button', { name: 'Approve and run', exact: true })).toBeVisible()
    await expect(alerts.getByText('Guardar alterações?', { exact: true })).toBeVisible()
    expect(await size(alerts.locator('.attention-card-detail'))).toBeCloseTo(body, 1)
    expect(await size(alerts.locator('.attention-card-severity'))).toBeGreaterThanOrEqual(11.5)
    await page.screenshot({ path: `test-results/content-${theme}-${density}.png` })
  })
}
test('UI scale remains proportional and preserves the edited field', async ({ page }) => {
  await page.goto('/e2e/workbench/fixture.html?surface=content&lang=en&scale=1.2')
  const field = page.getByRole('textbox', { name: 'Draft', exact: true })
  await field.fill('Saved local draft')
  const title = page.getByTestId('major-title')
  const font = await title.evaluate((node) => parseFloat(getComputedStyle(node).fontSize))
  expect(font).toBeCloseTo(14 * 1.32 * 1.2, 1)
  await page.getByRole('button', { name: 'Quick appearance', exact: true }).click()
  await page.getByRole('button', { name: 'Density: Compact', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(field).toHaveValue('Saved local draft')
  expect(await title.evaluate((node) => parseFloat(getComputedStyle(node).fontSize))).toBeCloseTo(font, 1)
})
