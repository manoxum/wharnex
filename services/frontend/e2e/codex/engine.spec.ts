import { expect, test } from '@playwright/test'
for (const theme of ['dark', 'light']) {
  test(`native host activity and interactive answers in ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width: 1100, height: 900 })
    await page.goto('/e2e/codex/fixture.html?native=1')
    await page.evaluate((theme) => { document.documentElement.dataset.theme = theme }, theme)
    await expect(page.getByText('developer@example.test', { exact: true })).toBeVisible()
    await expect(page.getByText('A localizar o limite de tentativas antes de alterar o código.')).toBeVisible()
    await expect(page.getByText('npm test -- retry')).toBeVisible()
    await page.getByText('Resultado', { exact: true }).click()
    await expect(page.getByText('3 testes passaram', { exact: true })).toBeVisible()
    await page.getByRole('combobox', { name: 'Esforço Codex' }).selectOption('xhigh')
    await expect(page.getByRole('combobox', { name: 'Esforço Codex' })).toHaveValue('xhigh')
    await page.getByRole('combobox', { name: 'Permissões Codex' }).selectOption('ask')
    await expect(page.getByRole('combobox', { name: 'Permissões Codex' })).toHaveValue('ask')
    await expect(page.getByRole('combobox', { name: /Contexto|Inteligência/ })).toHaveCount(0)
    await page.getByRole('button', { name: 'Pedir decisão de teste' }).click()
    await expect(page.getByText('Aguarda resposta', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Responder ao Codex' })).toBeDisabled()
    await page.getByRole('radio', { name: /Corrigir agora/ }).check()
    await page.screenshot({ path: `/tmp/wharnex-codex-native-question-${theme}.png` })
    await page.getByRole('button', { name: 'Responder ao Codex' }).click()
    await expect(page.getByText('Retry corrigido no projeto. Os 3 testes passaram.')).toBeVisible()
    await expect(page.getByRole('status').filter({ hasText: 'Concluído' })).toBeVisible()
    await expect(page.getByText(/Bundle entregue|bundle válido/)).toHaveCount(0)
    await page.setViewportSize({ width: 380, height: 850 })
    expect(await page.locator('#codex-owner').evaluate((node) => node.scrollWidth > node.clientWidth)).toBe(false)
    await page.screenshot({ path: `/tmp/wharnex-codex-native-narrow-${theme}.png` })
  })
  test(`native Codex account, streaming, limits and composer in ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width: 1100, height: 800 })
    await page.goto('/e2e/codex/fixture.html')
    await page.evaluate((theme) => { document.documentElement.dataset.theme = theme }, theme)
    await expect(page.getByText('developer@example.test')).toBeVisible()
    const appearance = await page.getByRole('button', { name: 'Atualizar Codex' }).evaluate((node) => ({ border: getComputedStyle(node).borderTopStyle, shadow: getComputedStyle(node).boxShadow }))
    expect(appearance).toEqual({ border: 'solid', shadow: 'none' })
    await expect(page.getByRole('switch', { name: 'Engine Codex' })).toHaveAttribute('aria-checked', 'true')
    await expect(page.getByRole('combobox', { name: 'Modelo Codex' })).toBeVisible()
    await page.getByRole('switch', { name: 'Engine Codex' }).click()
    await expect(page.getByRole('switch')).toHaveAttribute('aria-checked', 'false')
    await expect(page.getByRole('combobox', { name: 'Modelo Codex' })).toHaveCount(0)
    await page.getByRole('switch').click()
    await page.getByRole('button', { name: 'Concluir turno de teste' }).click()
    await expect(page.getByText('Validação concluída. O plano segue para o Wharnex.')).toBeVisible()
    await page.screenshot({ path: `/tmp/wharnex-codex-${theme}.png` })
    await page.getByRole('tab', { name: 'Consumo' }).click()
    await expect(page.getByRole('progressbar', { name: 'Uso da janela principal' })).toHaveAttribute('aria-valuenow', '24')
    await expect(page.getByText('38%')).toBeVisible()
    await page.setViewportSize({ width: 380, height: 800 })
    await expect(page.getByRole('switch')).toBeVisible()
    expect(await page.locator('#codex-owner').evaluate((node) => node.scrollWidth > node.clientWidth)).toBe(false)
    await page.screenshot({ path: `/tmp/wharnex-codex-narrow-${theme}.png` })
  })
}
test('manual quota continuation selects another account and retains Auto Evolution awareness', async ({ page }) => {
  await page.setViewportSize({ width: 1100, height: 1000 })
  await page.goto('/e2e/codex/fixture.html?native=1')
  await page.getByRole('button', { name: 'Simular quota esgotada' }).click()
  await expect(page.getByText('Auto Evolution', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continuar manualmente' })).toHaveAttribute('title', /renovação da quota/)
  await expect(page.getByText('Trabalho retomado com a Segunda conta.')).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Conta Codex' }).selectOption('second')
  await expect(page.getByText('second@example.test', { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Instruções de continuação Codex' })).toHaveCount(0)
  await page.screenshot({ path: '/tmp/wharnex-codex-native-continuation.png' })
  await page.getByRole('button', { name: 'Continuar manualmente' }).click()
  await expect(page.getByText('Trabalho retomado com a Segunda conta.')).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'Concluído' })).toBeVisible()
})
test('an older quota-interrupted conversation keeps its continue action visible outside long output', async ({ page }) => {
  await page.setViewportSize({ width: 1100, height: 840 })
  await page.goto('/e2e/codex/fixture.html?native=1&old-quota=1')
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark' })
  const continueButton = page.getByRole('button', { name: 'Continuar manualmente' })
  await expect(continueButton).toBeInViewport()
  expect(await continueButton.locator('svg').evaluate((node) => node.getBoundingClientRect().width)).toBe(14)
  const recovery = page.locator('[aria-label="Continuação manual Codex"]')
  expect(await recovery.evaluate((node) => {
    for (let parent = node.parentElement; parent; parent = parent.parentElement) if (getComputedStyle(parent).overflowY === 'auto') return true
    return false
  })).toBe(false)
  await page.setViewportSize({ width: 380, height: 800 })
  await expect(continueButton).toBeInViewport()
  await page.screenshot({ path: '/tmp/wharnex-codex-recovery-old-quota.png' })
  await page.getByRole('combobox', { name: 'Conta Codex' }).selectOption('second')
  await expect(page.getByText('second@example.test', { exact: true })).toBeVisible()
  await continueButton.click()
  await expect(page.getByText('Trabalho retomado com a Segunda conta.')).toBeVisible()
})
