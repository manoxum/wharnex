package automationhold

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"strings"
	"time"

	_ "github.com/jackc/pgx/v5/stdlib"
)

// The table follows SoT/DATABASE_IDENTIFIERS.md: numeric id, immutable sid and
// uid. The hold name is the sid, so an upsert keeps the row's identity.
const postgresSchema = `
CREATE TABLE IF NOT EXISTS wharnex_automation_holds (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sid text NOT NULL UNIQUE,
    uid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    active boolean NOT NULL DEFAULT false,
    held_until timestamptz,
    level integer NOT NULL DEFAULT 0,
    reason text NOT NULL DEFAULT '',
    source text NOT NULL DEFAULT '',
    updated_at timestamptz NOT NULL DEFAULT now()
);`

// Postgres is the durable hold store.
type Postgres struct {
	db      *sql.DB
	catalog Catalog
}

// OpenPostgres connects and ensures the schema.
func OpenPostgres(ctx context.Context, databaseURL string, catalog Catalog) (*Postgres, error) {
	db, err := sql.Open("pgx", databaseURL)
	if err != nil {
		return nil, errors.New("open automation holds: invalid database configuration")
	}
	db.SetMaxOpenConns(2)
	if err := db.PingContext(ctx); err != nil {
		db.Close()
		return nil, errors.New("connect automation holds: database is unavailable or rejected the credentials")
	}
	if _, err := db.ExecContext(ctx, postgresSchema); err != nil {
		db.Close()
		return nil, fmt.Errorf("initialize automation hold schema: %w", err)
	}
	return &Postgres{db: db, catalog: catalog}, nil
}

func (p *Postgres) Get(ctx context.Context, name string) (Hold, error) {
	if !p.catalog.Known(name) {
		return Hold{}, ErrUnknownHold
	}
	hold, err := scanHold(p.db.QueryRowContext(ctx, `SELECT `+holdColumns+` FROM wharnex_automation_holds WHERE sid=$1`, name))
	if errors.Is(err, sql.ErrNoRows) {
		return p.catalog.unset(name), nil
	}
	if err != nil {
		return Hold{}, fmt.Errorf("read automation hold %s: %w", name, err)
	}
	return hold, nil
}

func (p *Postgres) List(ctx context.Context) ([]Hold, error) {
	rows, err := p.db.QueryContext(ctx, `SELECT `+holdColumns+` FROM wharnex_automation_holds ORDER BY sid`)
	if err != nil {
		return nil, fmt.Errorf("list automation holds: %w", err)
	}
	defer rows.Close()
	var holds []Hold
	for rows.Next() {
		hold, err := scanHold(rows)
		if err != nil {
			return nil, fmt.Errorf("scan automation hold: %w", err)
		}
		holds = append(holds, hold)
	}
	return holds, rows.Err()
}

const holdColumns = `sid, uid::text, active, held_until, level, reason, source, updated_at`

func scanHold(row interface{ Scan(...any) error }) (Hold, error) {
	var hold Hold
	var until sql.NullTime
	if err := row.Scan(&hold.Name, &hold.UID, &hold.Active, &until, &hold.Level, &hold.Reason, &hold.Source, &hold.UpdatedAt); err != nil {
		return Hold{}, err
	}
	if until.Valid {
		hold.Until = &until.Time
	}
	return hold, nil
}

func (p *Postgres) Set(ctx context.Context, hold Hold) (Hold, error) {
	hold, err := p.catalog.Normalize(hold, time.Now().UTC())
	if err != nil {
		return Hold{}, err
	}
	_, err = p.db.ExecContext(ctx, `INSERT INTO wharnex_automation_holds
		(sid, active, held_until, level, reason, source, updated_at) VALUES ($1,$2,$3,$4,$5,$6,$7)
		ON CONFLICT (sid) DO UPDATE SET active=EXCLUDED.active, held_until=EXCLUDED.held_until,
			level=EXCLUDED.level, reason=EXCLUDED.reason, source=EXCLUDED.source, updated_at=EXCLUDED.updated_at`,
		hold.Name, hold.Active, hold.Until, hold.Level, hold.Reason, hold.Source, hold.UpdatedAt)
	if err != nil {
		return Hold{}, fmt.Errorf("save automation hold %s: %w", hold.Name, err)
	}
	return p.Get(ctx, hold.Name)
}

// Open returns the durable store when a database is configured and an
// in-memory one otherwise (unit tests, bare development).
func Open(databaseURL string, catalog Catalog) (Store, error) {
	if strings.TrimSpace(databaseURL) == "" {
		return NewMemory(catalog), nil
	}
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	return OpenPostgres(ctx, databaseURL, catalog)
}
