test('Worker live interaction uses bounded trusted IPC and fail-closed lifecycle cleanup', async () => {
  const source = await readDesktopIPCSource()
  const interaction = await readFile(new URL('../supervision/surface/worker-interaction.mjs', import.meta.url), 'utf8')
  const cleanup = await readFile(new URL('../../chatgpt/session/views/cleanup.mjs', import.meta.url), 'utf8')
  const viewHealthRuntime = await readFile(new URL('../../composition/session/view-health-runtime.mjs', import.meta.url), 'utf8')
  const workflowRuntime = await readFile(new URL('../../composition/session/workflow/runtime.mjs', import.meta.url), 'utf8')
  const createWindow = await readFile(new URL('../../window/lifecycle/create/window.mjs', import.meta.url), 'utf8')
  const windowRuntime = await readFile(new URL('../../composition/window/creation-runtime.mjs', import.meta.url), 'utf8')
  const agentSurfaces = await readFile(new URL('../../agent/ipc/surfaces.mjs', import.meta.url), 'utf8')
  const chatGPTStateIPC = await readFile(new URL('../../chatgpt/session/ipc/state.mjs', import.meta.url), 'utf8')
  const schedulingWiring = await readFile(new URL('../scheduling/wiring/desktop.mjs', import.meta.url), 'utf8')
  const preload = await readFile(new URL('../../preload.cjs', import.meta.url), 'utf8')
  const showStart = interaction.indexOf('function showChatAgentInteraction(agentID, rawBounds, windowState)')
  const showEnd = interaction.indexOf('\n  function setChatAgentInteractionBounds', showStart)
  const show = interaction.slice(showStart, showEnd)
  assert.match(source, /compose\(ctx, 'agent-scheduling', ctx\.createDesktopAgentScheduling, \{/)
  assert.match(schedulingWiring, /d\.createWorkerInteraction\(\{/)
  assert.match(show, /workerEntryForAgentID\(agentID\)/)
  assert.match(show, /normalizeBounds\(rawBounds, windowState\?\.window\?\.getContentBounds\?\.\(\)\)/)
  assert.match(show, /entry\.view\.setVisible\(true\)/)
  assert.match(createWindow, /hideChatAgentInteractionsForWindow\(state\)/)
  assert.match(await readDesktopCompositionSource(), /compose\(ctx, 'entrypoint', \(deps\) => \(\{ desktopEntrypoint: createDesktopEntrypointRuntime\(deps\) \}\)/)
  assert.match(windowRuntime, /createDesktopWindowCreator\(\{[\s\S]*hideChatAgentInteractionsForWindow: d\.hideChatAgentInteractionsForWindow/)
  assert.match(source, /compose\(ctx, 'chat-workflow', createDesktopChatWorkflowRuntime, \{/)
  assert.match(workflowRuntime, /createDesktopChatViewHealthRuntime\(\{/)
  assert.match(viewHealthRuntime, /createChatGPTViewCleanup\(\{/)
  assert.match(cleanup, /state\.activeAgentInteractionId = ''/)
  assert.match(source, /registerAgentIPC\(\{/)
  assert.match(agentSurfaces, /wharness:agents:interaction-open/)
  assert.match(agentSurfaces, /wharness:agents:interaction-bounds/)
  assert.match(agentSurfaces, /wharness:agents:interaction-close/)
  assert.match(agentSurfaces, /wharness:agents:open-devtools[\s\S]*workerEntryForAgentID\(request\?\.agentId\)[\s\S]*openDevTools\(\{ mode: 'detach', activate: true \}\)/)
  assert.match(source, /registerChatGPTSurfaceIPC\(\{/)
  assert.match(chatGPTStateIPC, /wharness:chatgpt:open-devtools[\s\S]*chatgptViews\.get\(key\)[\s\S]*ownerWindowId !== windowState\.id[\s\S]*requireOwnedChatGPTEntry\(key, entry\)[\s\S]*openDevTools\(\{ mode: 'detach', activate: true \}\)/)
  assert.match(preload, /openInteraction:/)
  assert.match(preload, /setInteractionBounds:/)
  assert.match(preload, /closeInteraction:/)
  assert.match(preload, /wharness:agents:open-devtools/)
  assert.match(preload, /wharness:chatgpt:open-devtools/)
})

test('Agents panel suspension uses the durable provider pause with optional deadline', async () => {
  const source = await readFile(new URL('../../agent/ipc/runtime.mjs', import.meta.url), 'utf8')
  const preload = await readFile(new URL('../../preload.cjs', import.meta.url), 'utf8')
  const start = source.indexOf("ipcMain.handle('wharness:agents:pause-provider'")
  const end = source.indexOf("ipcMain.handle('wharness:agents:resume-provider'", start)
  const handler = source.slice(start, end)

  assert.ok(start >= 0, 'pause-provider IPC handler must exist')
  assert.match(handler, /Date\.parse\(rawUntil\)/)
  assert.match(handler, /setProviderPause\(true, \{ pausedUntil, reason \}\)/)
  assert.match(handler, /deadline <= Date\.now\(\)/)
  assert.match(preload, /pauseProvider: \(pausedUntil\) => invoke\('wharness:agents:pause-provider'/)
})
