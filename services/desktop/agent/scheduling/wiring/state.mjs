export function createDesktopSchedulingState({ agentRuntime: agent, chatgptRuntime: chatgpt, windowRuntime: window }) {
  return {
    get desiredChatAgentWorkerSlots() { return agent.desiredChatAgentWorkerSlots },
    set desiredChatAgentWorkerSlots(value) { agent.desiredChatAgentWorkerSlots = value },
    get desiredChatAgentSupervisorSlots() { return agent.desiredChatAgentSupervisorSlots },
    set desiredChatAgentSupervisorSlots(value) { agent.desiredChatAgentSupervisorSlots = value },
    get configuredChatAgentWorkerSlots() { return agent.configuredChatAgentWorkerSlots },
    get configuredChatAgentSupervisorSlots() { return agent.configuredChatAgentSupervisorSlots },
    get chatAgentWorkerLastGrowAt() { return agent.chatAgentWorkerLastGrowAt },
    set chatAgentWorkerLastGrowAt(value) { agent.chatAgentWorkerLastGrowAt = value },
    get chatAgentSupervisorLastGrowAt() { return agent.chatAgentSupervisorLastGrowAt },
    set chatAgentSupervisorLastGrowAt(value) { agent.chatAgentSupervisorLastGrowAt = value },
    get chatAgentRuntimeDiagnostics() { return agent.chatAgentRuntimeDiagnostics },
    set chatAgentRuntimeDiagnostics(value) { agent.chatAgentRuntimeDiagnostics = value },
    get chatAgentScheduler() { return agent.chatAgentScheduler },
    get chatSupervisorScheduler() { return agent.chatSupervisorScheduler },
    get chatTranslatorScheduler() { return agent.chatTranslatorScheduler },
    get chatAgentPolicies() { return agent.chatAgentPolicies },
    get dueChatTranslations() { return agent.dueChatTranslations },
    set dueChatTranslations(value) { agent.dueChatTranslations = value },
    get quitting() { return window.quitting },
    get chatGPTRateLimitUntil() { return chatgpt.chatGPTRateLimitUntil },
    set chatGPTRateLimitUntil(value) { chatgpt.chatGPTRateLimitUntil = value },
    get chatGPTRateLimitResumeProbeRequired() { return chatgpt.chatGPTRateLimitResumeProbeRequired },
    set chatGPTRateLimitResumeProbeRequired(value) { chatgpt.chatGPTRateLimitResumeProbeRequired = value },
    get chatGPTRateLimitKind() { return chatgpt.chatGPTRateLimitKind },
    set chatGPTRateLimitKind(value) { chatgpt.chatGPTRateLimitKind = value },
    get chatGPTRateLimitAppliedAt() { return chatgpt.chatGPTRateLimitAppliedAt },
    set chatGPTRateLimitAppliedAt(value) { chatgpt.chatGPTRateLimitAppliedAt = value },
  }
}
