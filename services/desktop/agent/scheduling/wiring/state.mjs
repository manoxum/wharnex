export function createDesktopSchedulingState({ agentRuntime: agent, chatgptRuntime: chatgpt, windowRuntime: window }) {
  return {
    get desiredChatAgentWorkerSlots() { return agent.desiredWorkerSlots },
    set desiredChatAgentWorkerSlots(value) { agent.desiredWorkerSlots = value },
    get desiredChatAgentSupervisorSlots() { return agent.desiredSupervisorSlots },
    set desiredChatAgentSupervisorSlots(value) { agent.desiredSupervisorSlots = value },
    get configuredChatAgentWorkerSlots() { return agent.configuredWorkerSlots },
    get configuredChatAgentSupervisorSlots() { return agent.configuredSupervisorSlots },
    get chatAgentWorkerLastGrowAt() { return agent.workerLastGrowAt },
    set chatAgentWorkerLastGrowAt(value) { agent.workerLastGrowAt = value },
    get chatAgentSupervisorLastGrowAt() { return agent.supervisorLastGrowAt },
    set chatAgentSupervisorLastGrowAt(value) { agent.supervisorLastGrowAt = value },
    get chatAgentRuntimeDiagnostics() { return agent.diagnostics },
    set chatAgentRuntimeDiagnostics(value) { agent.diagnostics = value },
    get chatAgentScheduler() { return agent.workerScheduler },
    get chatSupervisorScheduler() { return agent.supervisorScheduler },
    get chatTranslatorScheduler() { return agent.translatorScheduler },
    get chatAgentPolicies() { return agent.policies },
    get dueChatTranslations() { return agent.dueTranslations },
    set dueChatTranslations(value) { agent.dueTranslations = value },
    get quitting() { return window.quitting },
    get chatGPTRateLimitUntil() { return chatgpt.rateLimitUntil },
    set chatGPTRateLimitUntil(value) { chatgpt.rateLimitUntil = value },
    get chatGPTRateLimitResumeProbeRequired() { return chatgpt.rateLimitResumeProbeRequired },
    set chatGPTRateLimitResumeProbeRequired(value) { chatgpt.rateLimitResumeProbeRequired = value },
    get chatGPTRateLimitKind() { return chatgpt.rateLimitKind },
    set chatGPTRateLimitKind(value) { chatgpt.rateLimitKind = value },
    get chatGPTRateLimitAppliedAt() { return chatgpt.rateLimitAppliedAt },
    set chatGPTRateLimitAppliedAt(value) { chatgpt.rateLimitAppliedAt = value },
  }
}
